-- 3. question_bank
--    Global table — questions with blueprints generated by the question engine.
--    No user_id — this is a shared question store.
--    Write access: service-role only (no user INSERT policy).
--    Read access: any authenticated user (for session reconstruction).
-- ──────────────────────────────────────────────────────────────────────────────

create table if not exists question_bank (
  id                  uuid primary key default gen_random_uuid(),
  domain              text not null check (domain in ('technical', 'hr', 'project')),
  category            text not null check (char_length(category) <= 100),
  subtopic            text not null check (char_length(subtopic) <= 100),
  difficulty          text not null
                      check (difficulty in ('easy','medium','hard','scenario','architecture')),
  question_type       text not null
                      check (question_type in (
                        'conceptual','scenario','debugging','coding',
                        'system_design','trade_off','security','performance'
                      )),
  question_text       text not null check (char_length(question_text) <= 2000),
  expected_concepts   jsonb not null default '[]'::jsonb,  -- string[]
  common_mistakes     jsonb not null default '[]'::jsonb,  -- string[]
  rubric              jsonb not null default '[]'::jsonb,  -- { concept, weight }[]
  source_evidence     jsonb not null default '[]'::jsonb,  -- { file, snippet }[] for project Qs
  model_version       text not null check (char_length(model_version) <= 50),
  prompt_version      text not null check (char_length(prompt_version) <= 50),
  created_at          timestamptz not null default now()
);

create index if not exists question_bank_domain_subtopic_idx
  on question_bank (domain, subtopic);

create index if not exists question_bank_domain_difficulty_idx
  on question_bank (domain, difficulty);

alter table question_bank enable row level security;

-- Authenticated users can read questions (for session replay / coaching)
create policy "authenticated users can read question bank"
  on question_bank for select
  using (auth.role() = 'authenticated');

-- NO insert/update/delete policy for regular users — service-role only

