-- 1. competency_scores
--    One row per (user, domain, competency). Upserted after every evaluation.
-- ──────────────────────────────────────────────────────────────────────────────

create table if not exists competency_scores (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid references auth.users on delete cascade not null,
  domain          text not null check (domain in ('technical', 'hr', 'project')),
  competency      text not null check (char_length(competency) <= 100),
  attempts        integer not null default 0 check (attempts >= 0),
  correct_weighted numeric(6,2) not null default 0 check (correct_weighted >= 0),
  last_score      integer check (last_score between 0 and 100),
  -- rolling average of last 3 scores stored as jsonb array for consistency calc
  recent_scores   jsonb not null default '[]'::jsonb,
  mastery_level   text not null default 'weak'
                  check (mastery_level in ('weak','developing','competent','strong','mastered')),
  updated_at      timestamptz not null default now()
);

create unique index if not exists competency_scores_user_domain_comp_idx
  on competency_scores (user_id, domain, competency);

create index if not exists competency_scores_user_domain_idx
  on competency_scores (user_id, domain);

create index if not exists competency_scores_mastery_idx
  on competency_scores (user_id, mastery_level);

alter table competency_scores enable row level security;

create policy "users can read own competency scores"
  on competency_scores for select
  using (auth.uid() = user_id);

create policy "users can insert own competency scores"
  on competency_scores for insert
  with check (auth.uid() = user_id);

create policy "users can update own competency scores"
  on competency_scores for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

